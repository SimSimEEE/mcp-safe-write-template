/**
 * End-to-end demo with a real MCP client over stdio against the built server.
 *
 *   npm run demo                       # prints a Markdown transcript
 *   npm run demo -- --out docs/demo.md # writes it to a file
 *   npx tsx scripts/demo.ts --quiet    # CI smoke test: assertions only
 *
 * Uses config/keys.example.json (demo keys whose secrets are public on purpose).
 */
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { parseArgs } from "node:util";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";

const { values } = parseArgs({
  options: { out: { type: "string" }, quiet: { type: "boolean" }, "skip-expiry": { type: "boolean" } },
});
const quiet = values.quiet ?? false;

const DEMO_KEYS = {
  operator: "demo-operator-key-NOT-A-SECRET",
  reader: "demo-reader-key-NOT-A-SECRET",
};

const auditFile = join(mkdtempSync(join(tmpdir(), "mcp-demo-")), "audit.jsonl");
const md: string[] = [];
const say = (s = "") => md.push(s);

function check(cond: unknown, what: string): void {
  if (!cond) {
    console.error(`demo assertion failed: ${what}`);
    process.exit(1);
  }
}

async function connect(secret: string, ttlSeconds = 300) {
  const stderr: string[] = [];
  const transport = new StdioClientTransport({
    command: process.execPath,
    args: ["dist/index.js"],
    env: {
      PATH: process.env.PATH ?? "",
      MCP_KEYS_FILE: "config/keys.example.json",
      MCP_API_KEY: secret,
      MCP_AUDIT_FILE: auditFile,
      MCP_PLAN_TTL_SECONDS: String(ttlSeconds),
    },
    stderr: "pipe",
  });
  transport.stderr?.on("data", (d: Buffer) => stderr.push(d.toString()));
  const client = new Client({ name: "demo-client", version: "0.1.0" });
  await client.connect(transport);
  return { client, stderr };
}

type Payload = Record<string, unknown> & { error?: { code: string } };

async function call(client: Client, name: string, args: Record<string, unknown>, label: string) {
  const r = await client.callTool({ name, arguments: args });
  const payload = r.structuredContent as Payload;
  say(`#### ${label}`);
  say();
  say("```text");
  say(`→ tools/call ${name} ${JSON.stringify(args)}`);
  say(`← isError=${String(r.isError)}`);
  say("```");
  say("```json");
  say(JSON.stringify(payload, null, 2));
  say("```");
  say();
  return { isError: r.isError === true, payload };
}

async function main() {
  say("# Demo: read → preview → confirm → execute → audit");
  say();
  say("Generated by `npm run demo -- --out docs/demo.md` — a real MCP client (`@modelcontextprotocol/sdk`)");
  say("talking to the built server (`node dist/index.js`) over stdio. Nothing here is hand-written.");
  say("Keys are the public demo keys from `config/keys.example.json`. Each connection spawns its own");
  say("server process, and the example store is in memory, so every connection starts from the same seed data.");
  say();

  // ---- operator session
  const op = await connect(DEMO_KEYS.operator);
  say("## 1. Server start (stderr)");
  say();
  await new Promise((r) => setTimeout(r, 200));
  say("```text");
  say(op.stderr.join("").replace(auditFile, "<tmp>/audit.jsonl").trim());
  say("```");
  say();

  const { tools } = await op.client.listTools();
  say("## 2. Tools the client sees");
  say();
  say("| tool | readOnlyHint | destructiveHint |");
  say("|---|---|---|");
  for (const t of tools) say(`| \`${t.name}\` | ${t.annotations?.readOnlyHint} | ${t.annotations?.destructiveHint} |`);
  say();
  check(tools.length === 6, "6 tools listed");

  say("## 3. Happy path (key: `demo-operator`)");
  say();
  const read = await call(op.client, "get_order", { order_id: "ord_1002" }, "3-1. Read the order");
  check(!read.isError, "read ok");

  const prev = await call(
    op.client,
    "preview_update_order_status",
    { order_id: "ord_1002", status: "shipped", reason: "picked up by courier" },
    "3-2. Preview the change (nothing is written yet)",
  );
  check(!prev.isError && prev.payload.plan_id, "preview ok");
  say("> The assistant shows `summary` and `changes` to the user and waits. The user answers “yes”.");
  say();

  const again = await call(op.client, "get_order", { order_id: "ord_1002" }, "3-3. Order is unchanged after preview");
  check((again.payload.order as { status: string }).status === "paid", "preview did not write");

  const exec = await call(
    op.client,
    "execute_plan",
    { plan_id: prev.payload.plan_id, content_hash: prev.payload.content_hash },
    "3-4. Execute with the confirmed plan_id + content_hash",
  );
  check(!exec.isError && (exec.payload.order as { status: string }).status === "shipped", "execute ok");

  say("## 4. What the safety rules refuse");
  say();
  const replay = await call(
    op.client,
    "execute_plan",
    { plan_id: prev.payload.plan_id, content_hash: prev.payload.content_hash },
    "4-1. Replaying the same plan",
  );
  check(replay.payload.error?.code === "plan_already_used", "replay refused");

  const p2 = await call(
    op.client,
    "preview_cancel_order",
    { order_id: "ord_1001", reason: "customer asked to cancel" },
    "4-2. A new preview (cancel)",
  );
  const wrongHash = "0".repeat(64);
  const mismatch = await call(
    op.client,
    "execute_plan",
    { plan_id: p2.payload.plan_id, content_hash: wrongHash },
    "4-3. Executing it with a hash that does not match what was confirmed",
  );
  check(mismatch.payload.error?.code === "hash_mismatch", "hash mismatch refused");

  const leaky = await call(
    op.client,
    "list_orders",
    { status: "pending", api_key: "sk-pasted-by-mistake" },
    "4-4. A call carrying a secret-looking argument (rejected; see how the audit line redacts it)",
  );
  check(leaky.payload.error?.code === "invalid_input", "unknown arg rejected");
  await op.client.close();

  const rd = await connect(DEMO_KEYS.reader);
  const denied = await call(
    rd.client,
    "preview_cancel_order",
    { order_id: "ord_1001", reason: "trying anyway" },
    "4-5. A read-only key (`demo-reader`) trying to write",
  );
  check(denied.payload.error?.code === "forbidden", "scope denied");
  await rd.client.close();

  if (!quiet && !values["skip-expiry"]) {
    const ex = await connect(DEMO_KEYS.operator, 10);
    const p3 = await call(
      ex.client,
      "preview_add_order_note",
      { order_id: "ord_1003", note: "left at the front desk" },
      "4-6. Preview with a 10 s TTL (server started with MCP_PLAN_TTL_SECONDS=10) …",
    );
    await new Promise((r) => setTimeout(r, 11_000));
    const expired = await call(
      ex.client,
      "execute_plan",
      { plan_id: p3.payload.plan_id, content_hash: p3.payload.content_hash },
      "4-7. … executed 11 s later",
    );
    check(expired.payload.error?.code === "plan_expired", "expiry refused");
    await ex.client.close();
  }

  say("## 5. Audit log (`audit.jsonl`, one line per call)");
  say();
  const lines = readFileSync(auditFile, "utf8").trim().split("\n");
  say("```jsonl");
  for (const l of lines) say(l);
  say("```");
  say();
  const raw = lines.join("\n");
  check(!raw.includes(DEMO_KEYS.operator) && !raw.includes(DEMO_KEYS.reader), "no API keys in audit log");
  check(!raw.includes("sk-pasted-by-mistake") && raw.includes('"api_key":"[REDACTED]"'), "argument redacted");
  say(`Checks run by the script: neither API key and no secret-looking argument value appears in the log`);
  say(`(${lines.length} lines); the \`api_key\` argument is stored as \`[REDACTED]\`.`);

  if (values.out) writeFileSync(values.out, `${md.join("\n")}\n`);
  else if (!quiet) console.log(md.join("\n"));
  if (quiet) console.log(`demo smoke test passed (${lines.length} audit lines)`);
}

main().catch((e: unknown) => {
  console.error(e);
  process.exit(1);
});
